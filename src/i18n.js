export function localize(root,language){
 const dictionary=language==='en'?esToEn:{...Object.fromEntries(Object.entries(esToEn).map(([es,en])=>[en,es])),...enToEsExtras};
 const walker=document.createTreeWalker(root,NodeFilter.SHOW_TEXT);
 const nodes=[];while(walker.nextNode())nodes.push(walker.currentNode);
 for(const node of nodes){
  if(node.parentElement?.closest('script,style,textarea,code,[data-no-translate]'))continue;
  const value=node.nodeValue,trimmed=value.trim(),translated=dictionary[trimmed];
  if(translated){const lead=value.match(/^\s*/)?.[0]||'',trail=value.match(/\s*$/)?.[0]||'';node.nodeValue=lead+translated+trail;}
 }
 for(const el of root.querySelectorAll('[placeholder],[aria-label]')){
  for(const attr of ['placeholder','aria-label']){const value=el.getAttribute(attr);if(value&&dictionary[value])el.setAttribute(attr,dictionary[value]);}
 }
 document.documentElement.lang=language;
}
